# ===== 缩放点积注意力（Scaled Dot-Product Attention）最简实现 =====
# 本文件是 02_Attention.py 的极简版，去掉了多头和投影，只保留核心 5 步。
# 整体流程：创建Q/K/V -> 点积 -> 缩放 -> softmax -> 加权求和
# 涉及知识：[[缩放点积注意力]]、[[点积与向量相似度]]

import torch
import torch.nn.functional as F

# ===== 第 1 段：创建 Q、K、V 张量 =====
# 做什么：直接创建三个随机张量（跳过线性投影，专注注意力计算本身）
# 注意：Q 的序列长度(3)和 K/V 的序列长度(4)不同 — 这是交叉注意力的场景
#   - 自注意力：Q/K/V 来自同一序列，序列长度相同
#   - 交叉注意力：Q 来自一个序列（如解码器），K/V 来自另一个序列（如编码器）
# 形状：Q = (B=2, S1=3, F=4), K = V = (B=2, S2=4, F=4)

q = torch.randn(2, 3, 4)  # Query: 3个查询（比如解码器的3个位置）
k = torch.randn(2, 4, 4)  # Key:   4个键（比如编码器的4个位置）
v = torch.randn(2, 4, 4)  # Value: 4个值（和 Key 来自同一序列）


# ===== 第 2 段：计算点积，得到原始注意力分数 =====
# 做什么：Q 和 K 做批量矩阵乘法，得到"每个查询对每个键的匹配分数"
# 原理：点积越大 -> 两个向量方向越一致 -> 匹配度越高
# 形状：bmm(Q, K^T) = (B, S1, F) x (B, F, S2) -> (B, S1, S2)
# 涉及知识：[[点积与向量相似度]]（为什么点积能衡量相似度）

# k.transpose(1, 2): (B=2, S2=4, F=4) -> (B=2, F=4, S2=4) — 转置才能乘
# bmm: 严格 3D 批量矩阵乘法（对比 matmul 支持 4D+广播）
raw_weights = torch.bmm(q, k.transpose(1, 2))  # (2, 3, 4) — 3个查询对4个键的分数


# ===== 第 3 段：缩放 =====
# 做什么：除以 sqrt(feature_dim)，防止点积值过大
# 为什么：维度越大 -> 点积值越大 -> softmax 输出越极端 -> 梯度消失
# 形状不变：(2, 3, 4)
# 涉及知识：[[缩放点积注意力]]（缩放的原因详解）

scaling_factor = q.size(-1) ** 0.5  # sqrt(4) = 2
scaled_weights = raw_weights / scaling_factor  # (2, 3, 4) — 形状不变


# ===== 第 4 段：softmax 归一化 =====
# 做什么：将每行变成概率分布（非负、和为1）
# dim=-1: 对最后一维（4个键）做 softmax
# 效果：每行从"原始匹配分数"变成"注意力分配比例"
# 形状不变：(2, 3, 4)
# 涉及知识：[[激活函数体系]]（Softmax在注意力中的特殊用法）

attn_weights = F.softmax(scaled_weights, dim=-1)  # (2, 3, 4) — 每行和为1


# ===== 第 5 段：加权求和 =====
# 做什么：用注意力权重对 V 加权，得到每个查询的输出
# 原理：匹配度高的 Value 贡献更多，匹配度低的贡献更少
# 形状：bmm(weights, V) = (B, S1, S2) x (B, S2, F) -> (B, S1, F)
# 涉及知识：[[缩放点积注意力]]（加权求和的含义）

attn_output = torch.bmm(attn_weights, v)  # (2, 3, 4) — 每个查询得到融合后的向量